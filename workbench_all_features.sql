-- ------------------------------------------------------- doctor_slots -------
CREATE TABLE IF NOT EXISTS doctor_slots (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    doctor_id    INT  NOT NULL,
    slot_date    DATE NOT NULL,
